function modelName = build_datacenter_simulink_model(targetModelName)
% BUILD_DATACENTER_SIMULINK_MODEL Programmatically builds the lumped-parameter
% data center thermal model in Simulink.
%
% Fixes MathWorks reviewer item #3:
%   - Uses correct standard Simulink library block paths:
%     'simulink/Sources/In1' (NOT 'simulink/Sources/Inport')
%     'simulink/Sinks/Out1'  (NOT 'simulink/Sinks/Outport')
%   - Configures signal logging directly on output ports
%   - Saves the version-controlled model under models/
%
% Syntax:
%   build_datacenter_simulink_model()
%   modelName = build_datacenter_simulink_model(targetModelName)
%
% Outputs:
%   modelName - Name of the created/configured Simulink model
%
% See also: setup_simulink_model, run_simulation, validate_plant_comparison

    if nargin < 1 || isempty(targetModelName)
        targetModelName = 'DataCenterLumpedPlant';
    end

    [mDir, mBase, ~] = fileparts(targetModelName);
    if isempty(mDir)
        modelsDir = fullfile(fileparts(mfilename('fullpath')), 'models');
        if ~exist(modelsDir, 'dir'), mkdir(modelsDir); end
        modelPath = fullfile(modelsDir, [mBase '.slx']);
    else
        modelPath = targetModelName;
    end
    modelName = mBase;

    % Check if Simulink is available
    if ~exist('new_system', 'file') && ~exist('new_system', 'builtin')
        fprintf('Note: Simulink is not available in this environment. Script ready for MATLAB.\n');
        return;
    end

    % Close if already open
    if bdIsLoaded(modelName)
        close_system(modelName, 0);
    end

    fprintf('Creating native Simulink model: %s...\n', modelName);
    new_system(modelName);
    open_system(modelName);

    % Solver settings
    set_param(modelName, 'Solver', 'ode45');
    set_param(modelName, 'StopTime', '432000'); % 5 days default
    set_param(modelName, 'SignalLogging', 'on');
    set_param(modelName, 'SignalLoggingName', 'logsout');
    set_param(modelName, 'ReturnWorkspaceOutputs', 'on');
    set_param(modelName, 'SaveTime', 'on');
    set_param(modelName, 'TimeSaveName', 'tout');

    % Add Inputs using correct Simulink In1 blocks
    add_block('simulink/Sources/In1', [modelName '/ServerLoad'], ...
        'Position', [50, 60, 80, 80], 'Port', '1');
    add_block('simulink/Sources/In1', [modelName '/AmbientTemp'], ...
        'Position', [50, 130, 80, 150], 'Port', '2');
    add_block('simulink/Sources/In1', [modelName '/CoolingCmd'], ...
        'Position', [50, 200, 80, 220], 'Port', '3');

    % Add MATLAB Function Block for Lumped-Parameter Plant Physics
    fcnPath = [modelName '/ThermalPlantODE'];
    add_block('simulink/User-Defined Functions/MATLAB Function', fcnPath, ...
        'Position', [170, 70, 360, 210]);

    % Populate MATLAB Function code
    chartId = sfroot;
    chart = chartId.find('-isa', 'Stateflow.EMChart', 'Path', fcnPath);
    if ~isempty(chart)
        chart.Script = sprintf([...
            'function [T_server, T_coolant, Flow_Rate, Pump_Power, Chiller_Power, Total_Cooling_Power] = ThermalPlantODE(util, Tamb, u)\n' ...
            '%% Lumped-parameter physical plant equations (matching Python ThermalPlant exactly)\n' ...
            'persistent T_room;\n' ...
            'if isempty(T_room)\n' ...
            '    T_room = 22.0;\n' ...
            'end\n' ...
            'dt_hr = 5.0 / 60.0;\n' ...
            'C_ROOM = 50.0;\n' ...
            'UA_ENV = 4.0;\n' ...
            'Q_IDLE = 150.0;\n' ...
            'Q_IT_MAX = 500.0;\n' ...
            'FAN_PEN_MAX = 30.0;\n' ...
            'FAN_RAMP_START = 25.0;\n' ...
            'FAN_RAMP_FULL = 32.0;\n' ...
            'Q_COOL_MAX = 600.0;\n' ...
            'P_FAN_MAX = 40.0;\n' ...
            'COP_CAP = 8.5;\n' ...
            'COP_FLOOR = 2.5;\n' ...
            'COP_SLOPE = 0.15;\n' ...
            'COP_REF_T = 10.0;\n\n' ...
            'u_ctrl = min(max(u, 0.0), 1.0);\n' ...
            'u_ut = min(max(util, 0.0), 1.0);\n' ...
            'ramp = min(max((T_room - FAN_RAMP_START)/(FAN_RAMP_FULL - FAN_RAMP_START), 0.0), 1.0);\n' ...
            'Qit = Q_IDLE + (Q_IT_MAX - Q_IDLE)*u_ut + FAN_PEN_MAX*(ramp^2);\n' ...
            'COP = min(max(COP_CAP - COP_SLOPE*(Tamb - COP_REF_T), COP_FLOOR), COP_CAP);\n' ...
            'Qdel = u_ctrl * Q_COOL_MAX;\n' ...
            'Pfan = P_FAN_MAX * (u_ctrl^3);\n' ...
            'Pchil = Qdel / COP;\n' ...
            'Ptot = Pfan + Pchil;\n\n' ...
            '%% RK4 integration step\n' ...
            'dTdt = @(t_in) (Q_IDLE + (Q_IT_MAX - Q_IDLE)*u_ut + FAN_PEN_MAX*(min(max((t_in - FAN_RAMP_START)/(FAN_RAMP_FULL - FAN_RAMP_START), 0), 1)^2) - Qdel + UA_ENV*(Tamb - t_in)) / C_ROOM;\n' ...
            'k1 = dTdt(T_room);\n' ...
            'k2 = dTdt(T_room + dt_hr/2 * k1);\n' ...
            'k3 = dTdt(T_room + dt_hr/2 * k2);\n' ...
            'k4 = dTdt(T_room + dt_hr * k3);\n' ...
            'T_room = T_room + dt_hr/6 * (k1 + 2*k2 + 2*k3 + k4);\n\n' ...
            'T_server = T_room;\n' ...
            'T_coolant = T_room - 5.0;\n' ...
            'Flow_Rate = u_ctrl * 25.0;\n' ...
            'Pump_Power = Pfan;\n' ...
            'Chiller_Power = Pchil;\n' ...
            'Total_Cooling_Power = Ptot;\n']);
    end

    % Add Outputs using correct Simulink Out1 blocks
    outNames = {'Server_Temp', 'Coolant_Temp', 'Flow_Rate', ...
                'Pump_Power', 'Chiller_Power', 'Total_Cooling_Power'};
    yPositions = [40, 80, 120, 160, 200, 240];

    for i = 1:numel(outNames)
        outPath = [modelName '/' outNames{i}];
        add_block('simulink/Sinks/Out1', outPath, ...
            'Position', [480, yPositions(i), 510, yPositions(i)+20], ...
            'Port', num2str(i));
    end

    % Connect lines
    add_line(modelName, 'ServerLoad/1', 'ThermalPlantODE/1');
    add_line(modelName, 'AmbientTemp/1', 'ThermalPlantODE/2');
    add_line(modelName, 'CoolingCmd/1', 'ThermalPlantODE/3');

    for i = 1:numel(outNames)
        lineH = add_line(modelName, ['ThermalPlantODE/' num2str(i)], [outNames{i} '/1']);
        set_param(lineH, 'Name', outNames{i});
        set_param(lineH, 'DataLogging', 'on');
        set_param(lineH, 'DataLoggingNameMode', 'Custom');
        set_param(lineH, 'DataLoggingNameCustom', outNames{i});
    end

    % Save and close
    save_system(modelName, modelPath);
    fprintf('Saved verified Simulink model to %s\n', modelPath);
end
